const FEATURED_COUNT = 3

export default function Testimonials() {
  const [showAll, setShowAll] = useState(false)
  const visibleReviews = showAll ? REVIEWS : REVIEWS.slice(0, FEATURED_COUNT)
  const hiddenCount = REVIEWS.length - FEATURED_COUNT

  return (
    <section id="testimonials" className="bg-white py-16 sm:py-24">
      <div className="mx-auto max-w-6xl px-4 sm:px-6">
        <p className="text-center font-heading text-sm font-bold uppercase tracking-wide text-primary">
          Отзывы
        </p>
        <h2 className="mt-2 text-center font-heading text-2xl font-extrabold text-sky-dark sm:text-3xl">
          Что говорят родители
        </h2>

        <div className="mt-12 grid gap-6 sm:grid-cols-2 lg:grid-cols-3 force-mobile:grid-cols-1!">
          {visibleReviews.map((review) => (
            <figure
              key={review.name}
              className="card-soft flex h-full flex-col justify-between bg-sky-light p-6"
            >
              <blockquote className="text-ink-soft">«{review.text}»</blockquote>
              <figcaption className="mt-4 font-heading font-bold text-sky-dark">
                {review.name}
              </figcaption>
            </figure>
          ))}
        </div>

        {hiddenCount > 0 && (
          <div className="mt-8 flex justify-center">
            <button
              type="button"
              onClick={() => setShowAll((value) => !value)}
              aria-expanded={showAll}
              className="btn-pill bg-primary px-6 py-3 text-sm text-white transition-transform hover:-translate-y-0.5 hover:bg-primary-dark"
            >
              {showAll ? 'Свернуть отзывы' : `Показать ещё отзывы (${hiddenCount})`}
            </button>
          </div>
        )}
      </div>
    </section>
  )
}
